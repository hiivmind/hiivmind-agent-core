from __future__ import annotations

from typing import Protocol

from .values import Brief, HandoverRequest, Message, ModelResponse, Outcome, RunEnd, ToolCall, ToolSpec


class NodeController(Protocol):
    async def handle(self, call: ToolCall) -> Outcome: ...
    async def responded(self, response: ModelResponse) -> None: ...
    async def stopped(self, said: str) -> str | None: ...


class NodeDriver(Protocol):
    async def drive(self, brief: Brief, controller: NodeController) -> RunEnd: ...


class ContextStrategy(Protocol):
    async def build(self, request: HandoverRequest) -> tuple[Message, ...]: ...


class ToolSource(Protocol):
    async def tools(self) -> tuple[ToolSpec, ...]: ...
    async def call(self, name: str, args: dict, state: dict) -> object: ...
    async def close(self) -> None: ...


class ResourceSource(Protocol):
    def read(self, path: str) -> str: ...
    def exists(self, path: str) -> bool: ...


class State(Protocol):
    def get(self, key: str) -> object: ...
    def set(self, key: str, value: object) -> None: ...


class StateStore(Protocol):
    def load(self, session: str) -> dict | None: ...
    def save(self, session: str, state: dict) -> None: ...


class Person(Protocol):
    async def tell(self, text: str) -> None: ...
    async def ask(self, question: str, label: str = "") -> str | None: ...  # None: nobody is there
